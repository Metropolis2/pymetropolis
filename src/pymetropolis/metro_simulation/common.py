from __future__ import annotations

from typing import TYPE_CHECKING

from pymetropolis.metro_pipeline.parameters import BoolParameter, FloatParameter, FractionParameter
from pymetropolis.metro_pipeline.steps import Step

if TYPE_CHECKING:
    from collections.abc import Mapping

    import polars as pl

    from pymetropolis.metro_pipeline import MetroFile
    from pymetropolis.modes import CarMode


def merge_populations(
    files: Mapping[str, MetroFile], id_columns: tuple[str, ...] = ("agent_id",)
) -> pl.DataFrame:
    """Reads a MetroDataFrameFile for each population and concatenates them vertically.

    Each column in `id_columns` is prefixed with `f"{population}-"` so that ids stay globally
    unique after the merge (a plain agent_id / trip_id is only unique within its own population's
    file).

    Columns missing in some populations are filled with nulls (e.g., the mode-choice columns of the
    agents of a single-mode population).
    """
    import polars as pl

    dfs = [
        f.read().with_columns(
            **{col: pl.concat_str(pl.lit(f"{population}-"), pl.col(col)) for col in id_columns}
        )
        for population, f in files.items()
    ]
    return pl.concat(dfs, how="diagonal_relaxed")


# Ridesharing passenger count is used for both vehicle types and trips so we create a Step for it.
class StepWithRidesharingCount(Step):
    ridesharing_passenger_count = FloatParameter(
        "vehicle_types.car.ridesharing_passenger_count",
        default=1.0,
        description="Average number of passengers in the car (excluding the driver).",
        note=(
            "This is only relevant for the `car_ridesharing` mode, and for the "
            "`car_driver_with_passengers` and `car_passenger` modes when "
            "`fuel.shared_with_passengers` is `true`. "
            "Larger values increase probability to select these modes (fuel cost is shared between "
            "more persons) and decrease congestion generated by `car_ridesharing` (more persons "
            "are traveling in each car)."
        ),
        lower_bound=0.0,
    )


class StepWithFuelSharing(StepWithRidesharingCount):
    """Mixin for Steps that need the share of the fuel cost paid by the travelers of car modes."""

    fuel_shared_with_passengers = BoolParameter(
        "fuel.shared_with_passengers",
        default=False,
        description=(
            'If `true`, the fuel cost of the "car_driver_with_passengers" and "car_passenger" '
            "modes is split equally among the driver and the passengers (like for "
            '"car_ridesharing"); otherwise, the driver pays the full fuel cost.'
        ),
        note="The number of passengers is `vehicle_types.car.ridesharing_passenger_count`.",
    )

    def fuel_share(self, mode: CarMode) -> float:
        """Share of the fuel cost of the car mode paid by the traveler."""
        assert self.ridesharing_passenger_count is not None
        return mode.get_fuel_share(
            self.ridesharing_passenger_count, bool(self.fuel_shared_with_passengers)
        )


class StepWithRidesharingSubsidy(Step):
    ridesharing_subsidy = FloatParameter(
        "ridesharing.subsidy",
        default=0.0,
        description="Monetary subsidy added to the utility of ridesharing (€ per trip).",
    )


class StepWithSimulationRatio(Step):
    simulation_ratio = FractionParameter(
        "simulation_ratio",
        default=1.0,
        description="Ratio of the population that is being simulated.",
        note=(
            "This value controls how road capacities and aggregate results are scaled when the "
            "simulated agents do not represent 100% of population. "
            "It does _not_ affect the scaling of the input origin-destination matrix or synthetic "
            "population."
        ),
    )
